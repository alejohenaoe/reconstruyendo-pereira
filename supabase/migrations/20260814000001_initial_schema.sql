-- ---------- Enums ----------
create type public.app_role as enum ('USER', 'ADMIN');
create type public.need_status as enum ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED');
create type public.help_offer_status as enum ('OFFERED', 'CONTACTED', 'AGREED', 'COMPLETED', 'CONFIRMED', 'CANCELLED');
create type public.image_kind as enum ('BEFORE', 'AFTER');
create type public.report_status as enum ('PENDING', 'REVIEWED', 'ACTIONED', 'DISMISSED');
create type public.report_reason as enum ('SUSPICIOUS', 'FALSE_INFO', 'SPAM', 'OFFENSIVE', 'FRAUD', 'MONEY_REQUEST', 'OTHER');
create type public.notification_type as enum ('HELP_OFFER', 'COMMENT', 'HELP_CONFIRMED', 'NEED_STATUS_CHANGE');

-- ---------- Catálogos ----------
create table public.municipalities (
  id smallint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique
);

create table public.capabilities (
  id smallint generated by default as identity primary key,
  slug text not null unique,
  label_es text not null
);

create table public.need_categories (
  id smallint generated by default as identity primary key,
  slug text not null unique,
  label_es text not null
);

